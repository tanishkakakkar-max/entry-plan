// Bundles the markdown files in /knowledge into generated TypeScript so they ship with the app
// on Vercel. Runs automatically before dev and build. Edit the .md files, never the generated ones.
//   lib/knowledge.generated.ts       instructions, sample plan, country research (server only)
//   lib/research.generated.ts        tagged research notes from knowledge/research (server only)
//   lib/examples-index.generated.ts  which saved example plans exist (tiny, loads with the page)
//   lib/examples.generated.ts        the saved example plans (loaded only when one is opened)
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const k = (p) => readFileSync(join(root, "knowledge", p), "utf8");

const countries = {};
for (const f of readdirSync(join(root, "knowledge", "countries"))) {
  if (f.endsWith(".md")) countries[f.replace(".md", "")] = k(join("countries", f));
}

// Saved example plans: knowledge/examples/<brand>-<country>.md
const BRANDS = ["olvae", "cava", "hero", "kalo"];
const COUNTRIES = ["japan", "singapore", "india", "us"];
const examples = {};
const exDir = join(root, "knowledge", "examples");
if (existsSync(exDir)) {
  for (const f of readdirSync(exDir)) {
    if (!f.endsWith(".md")) continue;
    const key = f.replace(".md", "");
    const [brand, country] = key.split("-");
    if (!BRANDS.includes(brand) || !COUNTRIES.includes(country) || key.split("-").length !== 2) {
      console.warn(`Skipping knowledge/examples/${f}: name it <brand>-<country>.md with brand ${BRANDS.join("/")} and country ${COUNTRIES.join("/")}.`);
      continue;
    }
    examples[key] = k(join("examples", f));
  }
}

// Research notes: knowledge/research/*.md with front matter like
//   ---
//   countries: [japan, singapore]   (or [all])
//   categories: [restaurants, food & beverage]   (or [all])
//   topics: [...]
//   updated: 2026-10-12
//   ---
// Only the tags are parsed here; matching happens per request in lib/research.ts.
const list = (v) =>
  (v ?? "")
    .replace(/^\[|\]$/g, "")
    .split(",")
    .map((x) => x.trim().toLowerCase())
    .filter(Boolean);
const research = [];
const resDir = join(root, "knowledge", "research");
if (existsSync(resDir)) {
  for (const f of readdirSync(resDir).sort()) {
    if (!f.endsWith(".md")) continue;
    const raw = k(join("research", f));
    const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
    if (!m) {
      console.warn(`Skipping knowledge/research/${f}: it needs front matter with countries and categories.`);
      continue;
    }
    const meta = Object.fromEntries(
      m[1].split("\n").map((line) => {
        const i = line.indexOf(":");
        return i < 0 ? [line.trim(), ""] : [line.slice(0, i).trim(), line.slice(i + 1).trim()];
      }),
    );
    research.push({
      file: f,
      countries: list(meta.countries),
      categories: list(meta.categories),
      topics: list(meta.topics),
      updated: meta.updated ?? "",
      body: raw.slice(m[0].length).trim(),
    });
  }
}

const header = "// AUTO-GENERATED by scripts/bundle-knowledge.mjs - do not edit.\n";
mkdirSync(join(root, "lib"), { recursive: true });
writeFileSync(
  join(root, "lib", "knowledge.generated.ts"),
  `${header}export const instructions = ${JSON.stringify(k("instructions.md"))};
export const samplePlan = ${JSON.stringify(k("sample-plan-olvae-japan.md"))};
export const countries: Record<string, string> = ${JSON.stringify(countries, null, 2)};
`,
);
writeFileSync(
  join(root, "lib", "research.generated.ts"),
  `${header}export type ResearchNote = { file: string; countries: string[]; categories: string[]; topics: string[]; updated: string; body: string };
export const researchNotes: ResearchNote[] = ${JSON.stringify(research, null, 2)};
`,
);
writeFileSync(
  join(root, "lib", "examples-index.generated.ts"),
  `${header}export const exampleKeys: string[] = ${JSON.stringify(Object.keys(examples).sort())};\n`,
);
writeFileSync(
  join(root, "lib", "examples.generated.ts"),
  `${header}export const examplePlans: Record<string, string> = ${JSON.stringify(examples, null, 2)};\n`,
);
console.log(
  `Bundled knowledge: ${Object.keys(countries).join(", ")} | research: ${research.length} notes | examples: ${Object.keys(examples).length} plans`,
);
